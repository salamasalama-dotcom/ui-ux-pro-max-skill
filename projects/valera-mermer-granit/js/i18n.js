const SUPPORTED_LANGS = ['tr', 'en'];

function getLang() {
  const saved = localStorage.getItem('valera-lang');
  return SUPPORTED_LANGS.includes(saved) ? saved : 'tr';
}

function t(key) {
  const lang = getLang();
  return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.tr[key] || key;
}

function applyI18n(lang) {
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (STRINGS[lang] && STRINGS[lang][key] !== undefined) {
      el.innerHTML = STRINGS[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (STRINGS[lang] && STRINGS[lang][key] !== undefined) {
      el.setAttribute('placeholder', STRINGS[lang][key]);
    }
  });
  document.querySelectorAll('.lang-toggle button').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem('valera-lang', lang);
  applyI18n(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  applyI18n(getLang());
  document.querySelectorAll('.lang-toggle button').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
  });
});
